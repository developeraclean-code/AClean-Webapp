-- component that downloads media, calls AI and creates a review suggestion.
BEGIN;

ALTER TABLE public.wa_payment_media_jobs
  ADD COLUMN IF NOT EXISTS manual_retry_count integer NOT NULL DEFAULT 0
    CHECK (manual_retry_count BETWEEN 0 AND 2),
  ADD COLUMN IF NOT EXISTS manual_retry_requested_at timestamptz,
  ADD COLUMN IF NOT EXISTS manual_retry_requested_by uuid,
  ADD COLUMN IF NOT EXISTS manual_retry_requested_name text;

CREATE TABLE IF NOT EXISTS public.wa_payment_media_retry_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  media_job_id uuid NOT NULL REFERENCES public.wa_payment_media_jobs(id) ON DELETE RESTRICT,
  requested_by uuid,
  requested_name text NOT NULL,
  previous_error_code text NOT NULL,
  retry_number integer NOT NULL CHECK (retry_number BETWEEN 1 AND 2),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_wa_payment_media_retry_audit_job
  ON public.wa_payment_media_retry_audit(media_job_id, created_at DESC);

ALTER TABLE public.wa_payment_media_retry_audit ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS wa_payment_media_retry_audit_service_all ON public.wa_payment_media_retry_audit;
CREATE POLICY wa_payment_media_retry_audit_service_all
  ON public.wa_payment_media_retry_audit FOR ALL TO service_role
  USING (true) WITH CHECK (true);
REVOKE ALL ON TABLE public.wa_payment_media_retry_audit FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.wa_payment_media_retry_audit TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.wa_payment_media_retry_audit_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.payment_media_retry_error_code(p_error text)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path=public,pg_temp AS $$
  SELECT CASE
    WHEN coalesce(p_error, '') ~* 'invalid_api_key|incorrect api key|authentication[_ ]?error|unauthorized' THEN 'invalid_api_key'
    WHEN coalesce(p_error, '') ~* 'credit_balance_exhausted|insufficient_quota|billing|quota' THEN 'provider_quota'
    WHEN coalesce(p_error, '') ~* 'rate.?limit|too many requests|(^|[^0-9])429([^0-9]|$)' THEN 'rate_limit'
    WHEN coalesce(p_error, '') ~* 'HTTP 5[0-9][0-9]|status 5[0-9][0-9]|server error|service unavailable|bad gateway|gateway timeout' THEN 'provider_5xx'
    WHEN coalesce(p_error, '') ~* 'timeout|timed out|aborted|deadline' THEN 'timeout'
    WHEN coalesce(p_error, '') ~* 'network|fetch failed|connection|ECONN|ENET|DNS' THEN 'network'
    ELSE 'not_retryable'
  END
$$;

CREATE OR REPLACE FUNCTION public.payment_media_manual_retry_eligible(
  p_status text,
  p_r2_key text,
  p_r2_url text,
  p_last_error text,
  p_manual_retry_count integer,
  p_has_suggestion boolean
) RETURNS boolean LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path=public,pg_temp AS $$
  SELECT p_status = 'FAILED_PERMANENT'
    AND nullif(btrim(p_r2_key), '') IS NOT NULL
    AND nullif(btrim(p_r2_url), '') IS NOT NULL
    AND coalesce(p_manual_retry_count, 0) < 2
    AND NOT coalesce(p_has_suggestion, false)
    AND public.payment_media_retry_error_code(p_last_error) <> 'not_retryable'
$$;

CREATE OR REPLACE FUNCTION public.request_wa_payment_media_retry(
  p_job_ids uuid[],
  p_actor_id uuid,
  p_actor_name text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE
  candidate record;
  requested_count integer := 0;
  input_count integer := 0;
  actor_name text := left(coalesce(nullif(btrim(p_actor_name), ''), 'Owner/Admin'), 120);
  error_code text;
BEGIN
  IF p_job_ids IS NULL OR cardinality(p_job_ids) = 0 THEN
    RAISE EXCEPTION 'At least one media job is required';
  END IF;
  SELECT count(DISTINCT value)::integer INTO input_count FROM unnest(p_job_ids) AS ids(value);
  IF input_count > 20 THEN RAISE EXCEPTION 'Maximum 20 media jobs per request'; END IF;

  FOR candidate IN
    SELECT j.*
    FROM public.wa_payment_media_jobs j
    WHERE j.id = ANY(p_job_ids)
      AND public.payment_media_manual_retry_eligible(
        j.status, j.r2_key, j.r2_url, j.last_error, j.manual_retry_count,
        EXISTS(SELECT 1 FROM public.payment_suggestions s WHERE s.media_job_id = j.id)
      )
    ORDER BY j.created_at, j.id
    FOR UPDATE OF j
  LOOP
    error_code := public.payment_media_retry_error_code(candidate.last_error);
    UPDATE public.wa_payment_media_jobs
      SET status = 'FAILED_RETRYABLE',
          attempts = 0,
          next_retry_at = now(),
          lease_token = NULL,
          lease_expires_at = NULL,
          manual_retry_count = candidate.manual_retry_count + 1,
          manual_retry_requested_at = now(),
          manual_retry_requested_by = p_actor_id,
          manual_retry_requested_name = actor_name,
          updated_at = now()
      WHERE id = candidate.id;

    INSERT INTO public.wa_payment_media_retry_audit(
      media_job_id, requested_by, requested_name, previous_error_code, retry_number
    ) VALUES (
      candidate.id, p_actor_id, actor_name, error_code, candidate.manual_retry_count + 1
    );
    requested_count := requested_count + 1;
  END LOOP;

  RETURN jsonb_build_object(
    'requested', requested_count,
    'skipped', input_count - requested_count
  );
END
$$;

REVOKE ALL ON FUNCTION public.payment_media_retry_error_code(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.payment_media_manual_retry_eligible(text,text,text,text,integer,boolean) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.request_wa_payment_media_retry(uuid[],uuid,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.payment_media_retry_error_code(text) TO service_role;
GRANT EXECUTE ON FUNCTION public.payment_media_manual_retry_eligible(text,text,text,text,integer,boolean) TO service_role;
GRANT EXECUTE ON FUNCTION public.request_wa_payment_media_retry(uuid[],uuid,text) TO service_role;

CREATE OR REPLACE FUNCTION public.get_payment_ingestion_health()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT jsonb_build_object(
   'generated_at',now(),
   'enabled',coalesce((SELECT value<>'false' FROM public.app_settings WHERE key='wa_payment_detect'),true),
   'last_worker_at',(SELECT max(started_at) FROM public.cron_runs WHERE task_name='payment-media-retry' AND status IN ('SUCCESS','SKIPPED')),
   'waiting',(SELECT count(*) FROM public.wa_payment_media_jobs WHERE status IN ('RECEIVED','STORED','FAILED_RETRYABLE','PROCESSING')),
   'overdue',(SELECT count(*) FROM public.wa_payment_media_jobs WHERE status IN ('RECEIVED','STORED','FAILED_RETRYABLE','PROCESSING') AND created_at<now()-interval '30 minutes'),
   'unsecured',(SELECT count(*) FROM public.wa_payment_media_jobs WHERE status IN ('RECEIVED','STORED','FAILED_RETRYABLE','PROCESSING') AND r2_key IS NULL),
   'failed',(SELECT count(*) FROM public.wa_payment_media_jobs WHERE status='FAILED_PERMANENT'),
   'recent_failed',(SELECT count(*) FROM public.wa_payment_media_jobs WHERE status='FAILED_PERMANENT' AND updated_at>now()-interval '24 hours'),
   'review',(SELECT count(*) FROM public.payment_suggestions WHERE status='PENDING' AND validation_status='PENDING'),
   'incidents',coalesce((SELECT jsonb_agg(to_jsonb(x)) FROM (
     SELECT j.id,j.phone,j.sender_name,j.status,j.category,j.attempts,j.last_error,j.r2_url,j.created_at,j.next_retry_at,
       j.manual_retry_count,
       EXISTS(SELECT 1 FROM public.payment_suggestions s WHERE s.media_job_id=j.id AND s.status='PENDING') AS has_suggestion,
       public.payment_media_manual_retry_eligible(
         j.status,j.r2_key,j.r2_url,j.last_error,j.manual_retry_count,
         EXISTS(SELECT 1 FROM public.payment_suggestions s WHERE s.media_job_id=j.id)
       ) AS can_manual_retry
     FROM public.wa_payment_media_jobs j
     WHERE j.status IN ('RECEIVED','STORED','FAILED_RETRYABLE','FAILED_PERMANENT','PROCESSING')
       OR (j.status='PENDING_REVIEW' AND EXISTS(SELECT 1 FROM public.payment_suggestions s WHERE s.media_job_id=j.id AND s.status='PENDING'))
     ORDER BY (j.status='FAILED_PERMANENT') DESC,j.created_at DESC,j.id LIMIT 50
   ) x),'[]'::jsonb)
 )
$$;
REVOKE ALL ON FUNCTION public.get_payment_ingestion_health() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.get_payment_ingestion_health() TO service_role;

NOTIFY pgrst,'reload schema';
COMMIT;
